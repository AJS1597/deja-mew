#!/usr/bin/env python3
"""Generate the monochrome graybox textures used by the project.

Everything produced here is a single flat colour on a transparent/opaque
background.  No art assets are generated by AI; these are pure graybox
placeholders that can be replaced later.

Usage:
    python3 tools/make_graybox_assets.py
"""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent

BACKGROUND = (21, 23, 28, 255)
TILE_GRAY = (92, 96, 104, 255)
CAT_GRAY = (230, 230, 230, 255)
EXIT_GREEN = (88, 196, 112, 255)


def solid_png(path: Path, size: tuple[int, int], colour: tuple[int, int, int, int]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    Image.new("RGBA", size, colour).save(path)
    print(f"wrote {path.relative_to(ROOT)} ({size[0]}x{size[1]})")


def main() -> None:
    solid_png(ROOT / "assets" / "tiles" / "tile_gray.png", (16, 16), TILE_GRAY)
    # The cat is drawn facing right. It is wider than tall so it reads as
    # walking on all fours; the player script rotates it for dashes.
    solid_png(ROOT / "assets" / "sprites" / "cat_graybox.png", (20, 12), CAT_GRAY)


if __name__ == "__main__":
    main()
